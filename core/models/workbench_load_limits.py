"""Load tiers tied to operation or task counts; every reader imports its tier from here."""

# 单次自动排产：所选批次展开后的工序数上限。排产前检查和开始排产准备按它把关。
MAX_SOLVE_OPERATIONS = 10000
# 排产记录里一类任务行的读取上限：单个候选方案的任务行、受理时存下的上一版正式计划行、受理决策基线里每道工序
# 最后一次正式安排的行（随历来正式计划累计），以及排产工时分解的条目。
MAX_RUN_RECORD_TASKS = 40000
# 单窗：一次读取或试调的工序、任务行数上限。计划读取与导出、报表、试调（基础范围、草稿行、执行保护范围、
# 采用历史的方案明细）和校准的待核对执行工序按它把关。
MAX_WINDOW_OPERATIONS = 20000
# 一个范围最多带的批次引用数。每道工序只属于一个批次，单窗的工序最多来自这么多批次，
# 所以行数合法的范围不会被批次数拦下。排产检查与排产偏好、试调采用复核和试调显示范围的批次列表，
# 现场实际甘特与现场记录的批次范围，批次页定位与「全选当前筛选」按它把关。
MAX_WINDOW_BATCHES = MAX_WINDOW_OPERATIONS
# 单窗读取的响应字节上限；20000 道工序的计划甘特图全节点约 7 MiB。
# 计划读取与导出、现场记录分页与撤销预览、报表中心按它把关。
MAX_WINDOW_RESPONSE_BYTES = 32 * 1024 * 1024
# 单窗报工事件上限，按 20000 道工序平均每道 2.5 条。现场实际甘特的报工条数、报表的报工及更正记录数按它把关。
MAX_WINDOW_REPORTS = 50000


# 提交的批次范围超过 MAX_WINDOW_BATCHES 时的统一提示。各入口传入自己比较时用的那个上限，拦截和提示始终是同一个数。
def too_many_batches(limit):
    return f"一次最多选 {limit} 个批次，请缩小范围后重试。"
